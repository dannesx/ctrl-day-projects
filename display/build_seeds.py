"""Regenerate the bundled Jokenpo screens from its bitmaps and installed GFX font."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
source = Path.home() / 'Arduino/libraries/Adafruit_GFX_Library/glcdfont.c'
font_source = re.sub(r'//[^\n]*|/\*.*?\*/', '', source.read_text(), flags=re.S)
font = [int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', font_source)]
bitmap = [int(x, 16) for x in re.findall(r'0x([0-9A-F]{2})', (ROOT.parent / 'jokenpo/hands.h').read_text())]
screens = []

def text(p, value, x, y, scale=1, color=1, wide_m=False):
    for n, c in enumerate(value):
        columns = [0x7F, 0x02, 0x04, 0x08, 0x04, 0x02, 0x7F] if wide_m and c == 'M' else font[ord(c)*5:ord(c)*5+5]
        for col, bits in enumerate(columns):
            for row in range(7):
                if bits & (1 << row):
                    for dy in range(scale):
                        for dx in range(scale):
                            xx, yy = x+(n*6+col)*scale+dx, y+row*scale+dy
                            if 0 <= xx < 128 and 0 <= yy < 64:
                                p[yy*128+xx] = color

def centered(p, value, y, scale=1, color=1, bold=True, left=0, area_width=128, wide_m=True):
    width = sum((8 if wide_m and c == "M" else 6)*scale+1 for c in value)-scale if bold else len(value)*6*scale
    x = left+(area_width-width)//2
    if bold:
        glyph_x = x
        for char in value:
            text(p, char, glyph_x, y, scale, color, wide_m)
            text(p, char, glyph_x+1, y, scale, color, wide_m)
            glyph_x += (8 if wide_m and char == 'M' else 6)*scale+1
    else:
        text(p, value, x, y, scale, color)

def add(name, p):
    screens.append({'id': f'jokenpo-{len(screens)}', 'name': name, 'pixels': p})

for cue in ('JO', 'KEN', 'PO!!'):
    p = [0]*8192
    centered(p, cue, 22, 5)
    add(cue, p)
names = ['Pedra', 'Papel', 'Tesoura']

def result(left, right):
    p = [1]*2048+[0]*6144
    heading = ('SEM JOGADA' if left < 0 else 'EMPATE!' if left == right
               else '> VOCE VENCEU <' if (left-right+3)%3 == 1 else 'ESP GANHOU!')
    centered(p, heading, 4, color=0, bold=True)
    for y in range(19, 62):
        p[y*128+64] = 1
    for column, choice in enumerate((left, right)):
        label = 'VOCE' if column == 0 else 'ESP32'
        centered(p, label, 20, left=column*64, area_width=64)
        if choice < 0:
            centered(p, '?', 30, 3, left=column*64, area_width=64)
            continue
        data = bitmap[choice*112:(choice+1)*112]
        for y in range(28):
            for x in range(32):
                p[(32+y)*128+column*64+16+x] = (data[y*4+x//8] >> (7-x%8)) & 1
    return p

for left in range(3):
    for right in range(3):
        add(f'{names[left]} × {names[right]}', result(left, right))

status_patches = []
for name, rows in (
    ('Conectando Wi-Fi', [('JOKENPO', 4), ('Conectando Wi-Fi', 24), ('Confira rede/senha', 44)]),
    ('Aguardando joinha · IP de exemplo', [('JOKENPO', 4), ('Faca um joinha', 22), ('para comecar', 34), ('192.168.1.100', 54)]),
):
    p = [0]*8192
    for value, y in rows:
        centered(p, value, y, bold=False)
        old, new = [0]*8192, [0]*8192
        centered(old, value, y, bold=True)
        centered(new, value, y, bold=False)
        status_patches.append({'name': name, 'offset': y*128,
                               'before': old[y*128:(y+7)*128],
                               'after': new[y*128:(y+7)*128]})
    add(name, p)

for right in range(3):
    add(f'Sem jogada × {names[right]}', result(-1, right))

revision = 'jokenpo-bold-v6'
project = {'format':'oled-studio','version':1,'width':128,'height':64,
           'activeId':screens[0]['id'],'screens':screens,
           'appliedBundles':[revision]}
data = json.dumps(project, ensure_ascii=False, separators=(',', ':'))
(ROOT / 'screens/jokenpo.json').write_text(data+'\n')
before, after = [1]*2048, [1]*2048
centered(before, '> VOCE VENCEU <', 4, color=0, bold=False)
centered(after, '> VOCE VENCEU <', 4, color=0, bold=True)
patch = json.dumps({'before':before, 'after':after}, separators=(',', ':'))
m_patches = []
for heading in ('EMPATE!', 'SEM JOGADA'):
    old, new = [1]*2048, [1]*2048
    centered(old, heading, 4, color=0, wide_m=False)
    centered(new, heading, 4, color=0)
    m_patches.append({'before': old, 'after': new})
m_patch = json.dumps(m_patches, separators=(',', ':'))
(ROOT / 'seeds.js').write_text('// Generated by build_seeds.py; editable interchange: screens/jokenpo.json\nconst OLED_SEEDS = '+data+';\nconst OLED_WIN_HEADER = '+patch+';\nconst OLED_M_HEADERS = '+m_patch+';\nconst OLED_STATUS_TEXT = '+json.dumps(status_patches, ensure_ascii=False, separators=(',', ':'))+';\n')
print(f'{len(screens)} screens generated')
