"""Rebuild the OLED hand bitmaps and their preview (requires Pillow)."""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent
SIZE = (32, 28)


def hand(kind):
    im = Image.new("1", SIZE)
    d = ImageDraw.Draw(im)
    # One-pixel outlines leave negative space between the fingers and palm.
    # Coordinates are authored at the physical 32x28 resolution, without AA.
    def outline(points):
        d.line(points, fill=1, width=1)

    if kind == "rock":
        # Four curled fingers with rounded knuckles; thumb crosses the front.
        outline([(7, 23), (5, 21), (4, 18), (4, 10), (5, 8),
                 (7, 7), (9, 7), (10, 5), (13, 5), (14, 4),
                 (17, 4), (19, 6), (22, 6), (24, 8), (25, 11),
                 (25, 17), (24, 20), (22, 23), (22, 26)])
        outline([(7, 23), (9, 24), (9, 26)])
        outline([(9, 8), (9, 13), (11, 15), (13, 15),
                 (14, 13), (14, 7)])
        outline([(14, 13), (16, 15), (18, 14), (19, 12), (19, 8)])
        outline([(19, 12), (21, 14), (23, 13)])
        outline([(5, 15), (8, 16), (12, 16), (15, 17),
                 (17, 19), (16, 21), (13, 21), (10, 20)])
        outline([(6, 12), (6, 14)])
    elif kind == "paper":
        # Palm in front view. Finger lengths differ and spread at the tips.
        outline([(10, 26), (10, 23), (7, 20), (3, 15), (2, 12),
                 (3, 11), (5, 11), (8, 15), (9, 15), (7, 6),
                 (7, 4), (8, 3), (10, 3), (11, 5), (13, 13),
                 (13, 3), (14, 1), (16, 1), (17, 3), (17, 12),
                 (19, 4), (20, 3), (22, 3), (23, 5), (21, 14),
                 (25, 8), (27, 7), (29, 9), (28, 12), (25, 18),
                 (24, 21), (21, 24), (21, 26)])
        outline([(10, 17), (12, 19), (12, 22)])
        outline([(15, 17), (19, 16), (22, 17)])
    else:
        # Index and middle finger form a V; folded fingers sit on the right.
        outline([(10, 26), (10, 24), (7, 21), (6, 18), (6, 16),
                 (7, 14), (9, 14), (12, 17)])
        outline([(10, 14), (6, 4), (6, 2), (7, 1), (9, 1),
                 (10, 3), (15, 13), (16, 13), (19, 3),
                 (20, 1), (22, 1), (23, 2), (23, 4), (20, 14)])
        outline([(20, 14), (22, 13), (24, 14), (24, 16),
                 (26, 16), (27, 18), (26, 21), (24, 24), (23, 26)])
        # A single diagonal thumb overlaps the curled ring and little fingers.
        outline([(12, 17), (16, 18), (19, 20), (18, 22),
                 (15, 22), (12, 21)])
        outline([(20, 15), (20, 18), (22, 19), (24, 18), (24, 16)])
    return im


hands = [hand(kind) for kind in ("rock", "paper", "scissors")]
lines = ["// Generated by art/generate.py. One bit per pixel, MSB first.",
         "#pragma once", "#include <Arduino.h>", "",
         "constexpr int HAND_WIDTH = 32;", "constexpr int HAND_HEIGHT = 28;",
         "const uint8_t HANDS[3][112] PROGMEM = {"]
for name, im in zip(("Pedra", "Papel", "Tesoura"), hands):
    lines.append("  { // " + name)
    data = im.tobytes()
    for start in range(0, len(data), 8):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[start:start + 8]) + ",")
    lines.append("  },")
lines.append("};")
(ROOT.parent / "hands.h").write_text("\n".join(lines) + "\n")

# Actual sprite coordinates; preview text uses Pillow's font, not Adafruit's.
preview = Image.new("RGB", (128 * 6, 64 * 6 * 3 + 24 * 2), "#101820")
for index, (left, right) in enumerate(((0, 2), (1, 0), (2, 1))):
    screen = Image.new("RGB", (128, 64))
    d = ImageDraw.Draw(screen)
    d.rectangle((0, 0, 127, 15), fill="#ffe353")
    d.text((23, 3), "> VOCE VENCEU <", fill="black", font_size=8)
    d.text((20, 20), "VOCE", fill="#39caff", font_size=8)
    d.text((83, 20), "ESP32", fill="#39caff", font_size=8)
    d.line((64, 19, 64, 61), fill="#39caff")
    for col, choice in enumerate((left, right)):
        screen.paste("#39caff", (col * 64 + 16, 32), hands[choice])
    preview.paste(screen.resize((768, 384), Image.Resampling.NEAREST),
                  (0, index * (384 + 24)))
preview.save(ROOT / "preview.png")
